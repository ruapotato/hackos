# HackOS -- generate the assembly source of the ROM file table: the programs
# that are part of the kernel image and appear, read-only, under /bin
# (fs/hvfs.ad reads the table).
#   mkromfs.sh OUT.S FILE...      each FILE becomes /bin/<basename of FILE>
set -euo pipefail
out="$1"; shift
{
    echo "/* Generated by scripts/mkromfs.sh -- do not edit. */"
    echo "        .section .rodata.romfs, \"a\", %progbits"
    echo "        .balign 4"
    echo "        .global romfs_count"
    echo "romfs_count:"
    echo "        .word   $#"
    echo "        .global romfs_table"
    echo "romfs_table:"
    n=0
    for f in "$@"; do
        echo "        .word   .Lname$n, .Ldata$n, .Lend$n - .Ldata$n, 0"
        n=$((n+1))
    done
    n=0
    for f in "$@"; do
        echo ".Lname$n: .asciz \"$(basename "$f")\""
        echo "        .balign 8"
        echo ".Ldata$n: .incbin \"$f\""
        echo ".Lend$n:"
        n=$((n+1))
    done
} > "$out"
